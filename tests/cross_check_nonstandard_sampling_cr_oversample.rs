fn djpeg_path() -> Option<PathBuf> {
    for p in [
        "/opt/homebrew/bin/djpeg",
        "/usr/local/bin/djpeg",
        "/usr/bin/djpeg",
        "/opt/libjpeg-turbo/bin/djpeg",
    ] {
        let pb = PathBuf::from(p);
        if pb.exists() {
            return Some(pb);
        }
    }
    None
}

/// Returns djpeg's (width, height, channels) for the fixture, or None.
fn djpeg_dims(djpeg: &PathBuf, jpeg: &[u8]) -> Option<(usize, usize, usize)> {
    let mut child = Command::new(djpeg)
        .arg("-pnm")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .ok()?;
    let mut stdin = child.stdin.take()?;
    let payload = jpeg.to_vec();
    let writer = std::thread::spawn(move || {
        let _ = stdin.write_all(&payload);
    });
    let out = child.wait_with_output().ok()?;
    let _ = writer.join();
    if !out.status.success() {
        return None;
    }
    let b = out.stdout;
    let channels = match &b[..2.min(b.len())] {
        b"P6" => 3,
        b"P5" => 1,
        _ => return None,
    };
    // parse "Px W H 255"
    let mut i = 0;
    let mut toks: Vec<String> = Vec::new();
    while toks.len() < 4 && i < b.len() {
        while i < b.len() && b[i].is_ascii_whitespace() {
            i += 1;
        }
        let s = i;
        while i < b.len() && !b[i].is_ascii_whitespace() {
            i += 1;
        }
        if s < i {
            toks.push(String::from_utf8(b[s..i].to_vec()).ok()?);
        }
    }
    Some((toks[1].parse().ok()?, toks[2].parse().ok()?, channels))
}

#[test]
fn strict_mode_rejects_chroma_oversampling() {
    let mut decoder = Decoder::new(FIXTURE).expect("header parse");
    // default = strict
    let err = decoder
        .decode_image()
        .expect_err("strict mode must reject Cr-oversamples-luma (unsupported)");
    let msg = format!("{err:?}");
    assert!(
        msg.contains("chroma upsample factor zero"),
        "unexpected strict-mode error: {msg}"
    );
}

#[test]
fn lenient_mode_recovers_with_warning_and_matches_djpeg_dims() {
    let mut decoder = Decoder::new(FIXTURE).expect("header parse");
    decoder.set_lenient(true);
    let img = decoder
        .decode_image()
        .expect("lenient mode must recover instead of rejecting");

    assert_eq!((img.width, img.height), (15, 9), "expected 15x9 output");
    assert_eq!(img.pixel_format, PixelFormat::Rgb);
    assert!(
        !img.warnings.is_empty(),
        "lenient recovery must record a warning (so the differential fuzzer skips)"
    );

    // Cross-validate that we are at least as accepting as djpeg, with matching
    // output dimensions (the drop-in floor the fuzzer enforces).
    let Some(djpeg) = djpeg_path() else {
        eprintln!("SKIP djpeg dim cross-check: djpeg not found");
        return;
    };
    if let Some((cw, ch, cc)) = djpeg_dims(&djpeg, FIXTURE) {
        assert_eq!(
            (cw, ch, cc),
            (img.width, img.height, 3),
            "lenient output dimensions must match djpeg's"
        );
    } else {
        eprintln!("SKIP: djpeg did not produce a PNM for the fixture");
    }
}
