//! Regression test for `fuzz_decode_diff_c` divergence on a 16x16 **baseline**
//! 4:1:1 (h=4,v=1) fixture found by scheduled Fuzz Smoke run 26618594605
//! (commit `f3c653fcb510f4fd5d23708b8ef7402af80f5df7`, 2026-05-29).
//!
//! Pins the 634-byte crash artifact `crash-23b88f318718fb51f8f5240596de33e50ca322d5`
//! against C `djpeg`. The original panic in `fuzz_decode_diff_c.rs:284`
//! reported `max abs diff = 223` (tolerance 24): the entire second MCU row
//! (rows 8-15) saturated to white where djpeg produced dark pixels.
//!
//! Root cause: on this corrupt bitstream the DC predictor runs away, so the
//! second MCU's luma DC coefficient dequantizes to ~11520. libjpeg-turbo's
//! SIMD `jpeg_idct_islow` keeps the pass-1 column workspace in **16-bit**
//! lanes — the "AC terms all zero" shortcut shifts the per-column DC with
//! `psllw PASS1_BITS`, which *wraps* (`11520 << 2 = 46080` -> i16 `-19456`),
//! yielding a dark pixel. Our scalar IDCT used an i32 workspace (matching C's
//! *non-SIMD* jidctint.c) and the x86 SSE2/AVX2 ports used i32 4-lane math, so
//! they kept the un-wrapped `46080` and saturated to white. The fix narrows
//! the scalar pass-1 workspace to i16 and routes this AC-all-zero shape through
//! the scalar IDCT in the SSE2/AVX2 cores. See
//! `src/decode/idct.rs::idct_8x8` and `src/simd/x86_64/{idct,avx2_idct}.rs`.
//!
//! The divergence was x86-SIMD-specific (verified bit-identical between C-x86
//! SSE2/AVX2 and C-AArch64 NEON), so this test only meaningfully exercises the
//! fix on x86_64 CI runners; on AArch64 the NEON path always agreed with djpeg.

