fn djpeg_path() -> Option<PathBuf> {
    for p in [
        "/opt/homebrew/bin/djpeg",
        "/usr/local/bin/djpeg",
        "/usr/bin/djpeg",
        "/opt/libjpeg-turbo/bin/djpeg",
    ] {
        let pb = PathBuf::from(p);
        if pb.exists() {
            return Some(pb);
        }
    }
    None
}

/// Mirror of `fuzz_decode_diff_c.rs::decode_with_djpeg`. Returns
/// `(w, h, channels, pixels, stderr_nonempty)`.
fn decode_with_djpeg(djpeg: &PathBuf, jpeg: &[u8]) -> Option<(usize, usize, usize, Vec<u8>, bool)> {
    let mut child = Command::new(djpeg)
        .arg("-pnm")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .ok()?;
    let mut stdin = child.stdin.take()?;
    let payload: Vec<u8> = jpeg.to_vec();
    let writer = std::thread::spawn(move || {
        let _ = stdin.write_all(&payload);
    });
    let out = child.wait_with_output().ok()?;
    let _ = writer.join();
    if !out.status.success() {
        return None;
    }
    let stderr_nonempty = !out.stderr.is_empty();
    let (w, h, c, px) = parse_pnm(&out.stdout)?;
    Some((w, h, c, px, stderr_nonempty))
}

fn parse_pnm(bytes: &[u8]) -> Option<(usize, usize, usize, Vec<u8>)> {
    let mut i: usize = 0;
    let mut tokens: Vec<String> = Vec::new();
    while tokens.len() < 4 && i < bytes.len() {
        while i < bytes.len() && bytes[i].is_ascii_whitespace() {
            i += 1;
        }
        let start = i;
        while i < bytes.len() && !bytes[i].is_ascii_whitespace() {
            i += 1;
        }
        if start < i {
            tokens.push(String::from_utf8(bytes[start..i].to_vec()).ok()?);
        }
    }
    if tokens.len() < 4 {
        return None;
    }
    let channels: usize = match tokens[0].as_str() {
        "P5" => 1,
        "P6" => 3,
        _ => return None,
    };
    let w: usize = tokens[1].parse().ok()?;
    let h: usize = tokens[2].parse().ok()?;
    if tokens[3] != "255" {
        return None;
    }
    i += 1;
    let needed = w.checked_mul(h)?.checked_mul(channels)?;
    if bytes.len() < i + needed {
        return None;
    }
    Some((w, h, channels, bytes[i..i + needed].to_vec()))
}

#[test]
fn fuzz_decode_diff_c_progressive_16x16_4_4_4_matches_djpeg() {
    let Some(djpeg) = djpeg_path() else {
        eprintln!("SKIP: djpeg not found on standard paths");
        return;
    };

    // Match the fuzz harness exactly: lenient mode + block_smoothing(true).
    // The harness enables block_smoothing to mirror djpeg's default behavior
    // for truncated progressive DC-only streams (PR #284, commit 24f8069).
    let mut decoder = Decoder::new(FUZZ_CRASH_BYTES).expect("rust decoder rejected fuzz input");
    decoder.set_lenient(true);
    decoder.set_block_smoothing(true);
    let img = decoder.decode_image().expect("rust decode_image failed");

    assert_eq!(
        img.width, 16,
        "expected 16x16 image, got {}x{}",
        img.width, img.height
    );
    assert_eq!(img.height, 16);
    assert_eq!(
        img.pixel_format,
        PixelFormat::Rgb,
        "expected RGB output for 3-component 4:4:4 progressive input"
    );
    let rust_pixels = img.data.clone();
    let r_lenient_recovery = !img.warnings.is_empty();

    let (cw, ch, cc, c_pixels, c_lenient_recovery) =
        decode_with_djpeg(&djpeg, FUZZ_CRASH_BYTES).expect("djpeg rejected fuzz input");

    assert_eq!(cw, 16);
    assert_eq!(ch, 16);
    assert_eq!(cc, 3);
    assert_eq!(c_pixels.len(), rust_pixels.len(), "byte count mismatch");

    // Compute divergence stats.
    let mut max_d: i32 = 0;
    let mut sum_d: i64 = 0;
    let mut first_diff_idx: Option<usize> = None;
    for (idx, (a, b)) in c_pixels.iter().zip(rust_pixels.iter()).enumerate() {
        let d: i32 = (*a as i32 - *b as i32).abs();
        if d != 0 && first_diff_idx.is_none() {
            first_diff_idx = Some(idx);
        }
        if d > max_d {
            max_d = d;
        }
        sum_d += d as i64;
    }
    let mean_d = sum_d as f64 / c_pixels.len() as f64;

    eprintln!(
        "ARCH=darwin-or-linux | lenient flags: rust={} c={} | max_diff={} mean_diff={:.3} first_diff_idx={:?}",
        r_lenient_recovery, c_lenient_recovery, max_d, mean_d, first_diff_idx
    );
    // Per-row dump to make CI-side x86_64 SIMD divergence easy to read.
    for row in 0..16 {
        let off = row * 16 * 3;
        let c_row: Vec<u8> = c_pixels[off..off + 48].to_vec();
        let r_row: Vec<u8> = rust_pixels[off..off + 48].to_vec();
        let row_max = c_row
            .iter()
            .zip(r_row.iter())
            .map(|(a, b)| (*a as i32 - *b as i32).abs())
            .max()
            .unwrap_or(0);
        if row_max == 0 {
            continue;
        }
        eprintln!(
            "row {:02} max_d={:3} | c={:?} | r={:?}",
            row, row_max, c_row, r_row
        );
    }

    // After the fix, the IDCT tolerance budget is the standard ±2 per byte
    // for clean inputs (matches the harness's lossless-IDCT ceiling, not the
    // 24-tolerance fuzz floor which absorbs successive-approximation noise).
    // The pre-fix divergence was max_d=40 on this fixture (CI run 25900537973).
    assert!(
        max_d <= 2,
        "Rust vs djpeg disagree on this fuzz fixture: max_diff={} mean_diff={:.3}",
        max_d,
        mean_d,
    );
}

