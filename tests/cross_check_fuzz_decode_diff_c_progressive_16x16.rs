#[test]
fn progressive_16x20_multi_imcu_row_partial_last_smoothing_matches_djpeg() {
    let Some(djpeg) = djpeg_path() else {
        eprintln!("SKIP: djpeg not found on standard paths");
        return;
    };

    let mut decoder = Decoder::new(MULTI_IMCU_ROW_PARTIAL_LAST_BYTES)
        .expect("rust decoder rejected multi-iMCU-row fixture");
    decoder.set_lenient(true);
    decoder.set_block_smoothing(true);
    let img = decoder.decode_image().expect("rust decode_image failed");

    assert_eq!((img.width, img.height), (16, 20), "expected 16x20");
    assert_eq!(img.pixel_format, PixelFormat::Rgb);
    let rust_pixels = img.data.clone();

    let (cw, ch, cc, c_pixels, _c_lenient_recovery) =
        decode_with_djpeg(&djpeg, MULTI_IMCU_ROW_PARTIAL_LAST_BYTES)
            .expect("djpeg rejected multi-iMCU-row fixture");

    assert_eq!((cw, ch, cc), (16, 20, 3), "djpeg dims");
    assert_eq!(c_pixels.len(), rust_pixels.len(), "byte count mismatch");

    let mut max_d: i32 = 0;
    for (a, b) in c_pixels.iter().zip(rust_pixels.iter()) {
        max_d = max_d.max((*a as i32 - *b as i32).abs());
    }

    // Smoothing is active on this fixture (C smooth-on vs smooth-off
    // differs by 4), and coefficient decode is identical on both sides,
    // so the smoothed output must be byte-exact. A naive real-grid row
    // clamp measures max_d = 2 here; the padded-grid clamp measures 2.
    assert_eq!(
        max_d, 0,
        "multi-iMCU-row smoothing must follow C's per-iMCU-row \
         image_block_row clamping: max abs diff = {}",
        max_d
    );
}

