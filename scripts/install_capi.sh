#!/usr/bin/env bash
# install_capi.sh — stage `libjpeg-turbo-rs-capi`'s cdylib + headers +
# pkg-config + CMake config into a DESTDIR/PREFIX tree the way
# distro packagers expect.
#
# This is the P2-8 install path: it produces the layout that
# `pkg-config --libs libjpeg`, `find_package(JPEG)`, and consumers like
# Pillow / ImageMagick / libvips expect when our cdylib is dropped in
# place of upstream `libjpeg.so.62` / `libturbojpeg.so.0`.
#
# Usage:
#   scripts/install_capi.sh --destdir /tmp/install --prefix /usr
#
# Required env vs CLI flags (CLI wins):
#   --destdir DIR     Stage root (defaults to "")
#   --prefix DIR      Install prefix (defaults to "/usr/local")
#   --soname NAME     libjpeg "major" SONAME on Linux (default
#                     "libjpeg.so.62"; pass "libjpeg.so.8" for the v8
#                     SONAME the docs/ABI_COMPATIBILITY.md flags as the
#                     production-safe choice). On macOS, accepts the
#                     compat dylib name (default "libjpeg.62.dylib").
#                     The real cdylib filename is derived as
#                     "${soname}.${version}" (Linux) or
#                     "${soname%.dylib}.${version}.dylib" (macOS).
#   --soname-tj NAME  libturbojpeg "major" SONAME (default
#                     "libturbojpeg.so.0" / "libturbojpeg.0.dylib").
#   --build           Build the cdylib first (default: skip; assumes
#                     `target/release/liblibjpeg_turbo_rs_capi.{dylib,so}`
#                     already exists)
#
# Layout produced under ${DESTDIR}${PREFIX}:
#   lib/libjpeg.so.62.X.Y          actual cdylib
#   lib/libjpeg.so.62              symlink → .X.Y
#   lib/libjpeg.so                 symlink → libjpeg.so.62
#   lib/libturbojpeg.so.0.X.Y      hardlink/copy of the cdylib
#   lib/libturbojpeg.so.0          symlink → .X.Y
#   lib/libturbojpeg.so            symlink → libturbojpeg.so.0
#   lib/pkgconfig/libjpeg.pc       generated by build.rs (re-staged here)
#   lib/pkgconfig/libturbojpeg.pc  generated by build.rs (re-staged here)
#   lib/cmake/JPEG/JPEGConfig.cmake  CMake `find_package(JPEG)` shim
#   include/jpeglib.h              from references/libjpeg-turbo/src/
#   include/jerror.h               from references/libjpeg-turbo/src/
#   include/jmorecfg.h             from references/libjpeg-turbo/src/
#   include/jconfig.h              generated (matches build.rs's v8 defaults)
#   include/turbojpeg.h            from references/libjpeg-turbo/src/

set -euo pipefail

DESTDIR=""
PREFIX="/usr/local"
SONAME=""
SONAME_TJ=""
DO_BUILD=0
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --destdir)    DESTDIR="$2"; shift 2 ;;
        --prefix)     PREFIX="$2"; shift 2 ;;
        --soname)     SONAME="$2"; shift 2 ;;
        --soname-tj)  SONAME_TJ="$2"; shift 2 ;;
        --build)      DO_BUILD=1; shift ;;
        --root)       ROOT="$2"; shift 2 ;;
        -h|--help)
            sed -n '2,/^set -euo/p' "$0" | sed 's/^# *//'
            exit 0
            ;;
        *) echo "unknown arg: $1" >&2; exit 1 ;;
    esac
done

OS_NAME="$(uname -s)"
case "$OS_NAME" in
    Linux*)  PLATFORM=linux ;;
    Darwin*) PLATFORM=macos ;;
    *) echo "unsupported platform: $OS_NAME" >&2; exit 1 ;;
esac

# Resolve cdylib path + version from Cargo.toml.
CDYLIB_VERSION="$(grep '^version' "$ROOT/crates/libjpeg-turbo-rs-capi/Cargo.toml" | head -1 | sed 's/.*"\(.*\)".*/\1/')"
case "$PLATFORM" in
    linux)
        CDYLIB_FILE="$ROOT/target/release/liblibjpeg_turbo_rs_capi.so"
        DEFAULT_LIBJPEG_MAJOR="libjpeg.so.62"
        DEFAULT_LIBJPEG_DEV="libjpeg.so"
        DEFAULT_LIBTJ_MAJOR="libturbojpeg.so.0"
        DEFAULT_LIBTJ_DEV="libturbojpeg.so"
        ;;
    macos)
        CDYLIB_FILE="$ROOT/target/release/liblibjpeg_turbo_rs_capi.dylib"
        DEFAULT_LIBJPEG_MAJOR="libjpeg.62.dylib"
        DEFAULT_LIBJPEG_DEV="libjpeg.dylib"
        DEFAULT_LIBTJ_MAJOR="libturbojpeg.0.dylib"
        DEFAULT_LIBTJ_DEV="libturbojpeg.dylib"
        ;;
esac

# Honor --soname / --soname-tj overrides.
LIBJPEG_MAJOR="${SONAME:-$DEFAULT_LIBJPEG_MAJOR}"
LIBTJ_MAJOR="${SONAME_TJ:-$DEFAULT_LIBTJ_MAJOR}"

# Derive the real (versioned) cdylib filename from the major SONAME.
# Linux: append .${VERSION} (e.g. libjpeg.so.8 → libjpeg.so.8.X.Y).
# macOS: insert ${VERSION} before the .dylib suffix (e.g. libjpeg.8.dylib
#        → libjpeg.8.X.Y.dylib).
# Derive the bare dev-link filename: drop everything from the SONAME
# digit onward (Linux) or the major digit before .dylib (macOS) so
# packagers passing a non-default --soname still get a sensible
# `libjpeg.{so,dylib}` symlink at the top of the chain.
case "$PLATFORM" in
    linux)
        LIBJPEG_REAL="${LIBJPEG_MAJOR}.${CDYLIB_VERSION}"
        LIBTJ_REAL="${LIBTJ_MAJOR}.${CDYLIB_VERSION}"
        # Strip everything after `.so` to get the dev link.
        LIBJPEG_DEV="${LIBJPEG_MAJOR%%.so*}.so"
        LIBTJ_DEV="${LIBTJ_MAJOR%%.so*}.so"
        ;;
    macos)
        LIBJPEG_REAL="${LIBJPEG_MAJOR%.dylib}.${CDYLIB_VERSION}.dylib"
        LIBTJ_REAL="${LIBTJ_MAJOR%.dylib}.${CDYLIB_VERSION}.dylib"
        # Strip the version digits before .dylib to get the dev link.
        # `libjpeg.62.dylib` → `libjpeg.dylib`.
        LIBJPEG_DEV="$(echo "$LIBJPEG_MAJOR" | sed 's/\.[0-9][0-9]*\.dylib$/.dylib/')"
        LIBTJ_DEV="$(echo "$LIBTJ_MAJOR" | sed 's/\.[0-9][0-9]*\.dylib$/.dylib/')"
        ;;
esac

# Replace the now-unused defaults with the resolved names so the
# install/symlink steps below pick them up.
DEFAULT_LIBJPEG_REAL="$LIBJPEG_REAL"
DEFAULT_LIBJPEG_MAJOR="$LIBJPEG_MAJOR"
DEFAULT_LIBJPEG_DEV="$LIBJPEG_DEV"
DEFAULT_LIBTJ_REAL="$LIBTJ_REAL"
DEFAULT_LIBTJ_MAJOR="$LIBTJ_MAJOR"
DEFAULT_LIBTJ_DEV="$LIBTJ_DEV"

if [[ "$DO_BUILD" -eq 1 || ! -f "$CDYLIB_FILE" ]]; then
    (cd "$ROOT" && cargo build -p libjpeg-turbo-rs-capi --release)
fi
[[ -f "$CDYLIB_FILE" ]] || { echo "cdylib not found: $CDYLIB_FILE" >&2; exit 1; }

# Stage roots.
LIBDIR="${DESTDIR}${PREFIX}/lib"
INCDIR="${DESTDIR}${PREFIX}/include"
PKGCFGDIR="${LIBDIR}/pkgconfig"
CMAKEDIR="${LIBDIR}/cmake/JPEG"
mkdir -p "$LIBDIR" "$INCDIR" "$PKGCFGDIR" "$CMAKEDIR"

# Install cdylib + symlink chains.
install -m 0755 "$CDYLIB_FILE" "${LIBDIR}/${DEFAULT_LIBJPEG_REAL}"
ln -sf "$DEFAULT_LIBJPEG_REAL" "${LIBDIR}/${DEFAULT_LIBJPEG_MAJOR}"
ln -sf "$DEFAULT_LIBJPEG_MAJOR" "${LIBDIR}/${DEFAULT_LIBJPEG_DEV}"
# libturbojpeg shares the same binary (we export both APIs).
install -m 0755 "$CDYLIB_FILE" "${LIBDIR}/${DEFAULT_LIBTJ_REAL}"
ln -sf "$DEFAULT_LIBTJ_REAL" "${LIBDIR}/${DEFAULT_LIBTJ_MAJOR}"
ln -sf "$DEFAULT_LIBTJ_MAJOR" "${LIBDIR}/${DEFAULT_LIBTJ_DEV}"

# Install upstream headers (verbatim — we are ABI-compatible with the
# v8 layout from references/libjpeg-turbo/src/jpeglib.h).
for header in jpeglib.h jerror.h jmorecfg.h turbojpeg.h; do
    install -m 0644 "$ROOT/references/libjpeg-turbo/src/$header" "$INCDIR/$header"
done

# jconfig.h: generate from the v8 defaults the build.rs / shim assume.
cat >"$INCDIR/jconfig.h" <<'EOF'
/* Generated by scripts/install_capi.sh — matches libjpeg-turbo-rs-capi
 * struct layout (JPEG_LIB_VERSION = 80, v8 ABI).
 *
 * See docs/ABI_COMPATIBILITY.md for the policy: consumers compiled
 * against this header link against our cdylib; consumers that need v6b
 * struct layout must use upstream libjpeg-turbo built without
 * WITH_JPEG7/WITH_JPEG8.
 */
#define JPEG_LIB_VERSION 80
#define LIBJPEG_TURBO_VERSION 3.1.0
#define LIBJPEG_TURBO_VERSION_NUMBER 3001000
#define C_ARITH_CODING_SUPPORTED 1
#define D_ARITH_CODING_SUPPORTED 1
#define MEM_SRCDST_SUPPORTED 1
#define WITH_SIMD 1
#ifndef BITS_IN_JSAMPLE
#define BITS_IN_JSAMPLE 8
#endif
EOF
chmod 0644 "$INCDIR/jconfig.h"

# Re-stage the build.rs-generated .pc files. We cannot read OUT_DIR
# directly (it's per-build), so regenerate from the same template here
# with the right ${prefix} substitution baked in.
cat >"$PKGCFGDIR/libjpeg.pc" <<EOF
prefix=${PREFIX}
exec_prefix=\${prefix}
libdir=\${prefix}/lib
includedir=\${prefix}/include

Name: libjpeg
Description: A SIMD-accelerated JPEG codec (libjpeg-turbo-rs shim)
Version: ${CDYLIB_VERSION}
Libs: -L\${libdir} -ljpeg
Cflags: -I\${includedir}
EOF

cat >"$PKGCFGDIR/libturbojpeg.pc" <<EOF
prefix=${PREFIX}
exec_prefix=\${prefix}
libdir=\${prefix}/lib
includedir=\${prefix}/include

Name: libturbojpeg
Description: A SIMD-accelerated JPEG codec (TurboJPEG API, libjpeg-turbo-rs shim)
Version: ${CDYLIB_VERSION}
Libs: -L\${libdir} -lturbojpeg
Cflags: -I\${includedir}
EOF

# Minimal CMake config so `find_package(JPEG)` resolves to our tree.
# Mirrors what FindJPEG.cmake produces but as a config-package so the
# user can pin to us via -DCMAKE_PREFIX_PATH=${PREFIX}.
cat >"$CMAKEDIR/JPEGConfig.cmake" <<EOF
# JPEG config package for libjpeg-turbo-rs-capi. Provides the variables
# and imported target FindJPEG.cmake exposes, so downstream
# CMake projects using \`find_package(JPEG)\` resolve here when
# \${CMAKE_PREFIX_PATH} points at this prefix.
set(JPEG_VERSION "${CDYLIB_VERSION}")
set(JPEG_INCLUDE_DIR "${PREFIX}/include")
set(JPEG_INCLUDE_DIRS "\${JPEG_INCLUDE_DIR}")
set(JPEG_LIBRARY "${PREFIX}/lib/${DEFAULT_LIBJPEG_DEV}")
set(JPEG_LIBRARIES "\${JPEG_LIBRARY}")
set(JPEG_FOUND TRUE)

if(NOT TARGET JPEG::JPEG)
    add_library(JPEG::JPEG UNKNOWN IMPORTED)
    set_target_properties(JPEG::JPEG PROPERTIES
        IMPORTED_LOCATION "\${JPEG_LIBRARY}"
        INTERFACE_INCLUDE_DIRECTORIES "\${JPEG_INCLUDE_DIR}"
    )
endif()
EOF

cat <<EOF
Installed libjpeg-turbo-rs-capi ${CDYLIB_VERSION} into ${DESTDIR}${PREFIX}:
  lib/${DEFAULT_LIBJPEG_REAL}    (cdylib)
  lib/${DEFAULT_LIBJPEG_MAJOR}, lib/${DEFAULT_LIBJPEG_DEV}    (symlinks)
  lib/${DEFAULT_LIBTJ_REAL}, lib/${DEFAULT_LIBTJ_MAJOR}, lib/${DEFAULT_LIBTJ_DEV}
  lib/pkgconfig/{libjpeg,libturbojpeg}.pc
  lib/cmake/JPEG/JPEGConfig.cmake
  include/{jpeglib,jerror,jmorecfg,jconfig,turbojpeg}.h
EOF
