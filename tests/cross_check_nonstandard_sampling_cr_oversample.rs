//! Regression test for LAST_MILE P4-21: a baseline JPEG whose Cr component
//! out-samples luma (`Y=h1v1, Cb=h1v1, Cr=h3v1`, so `Hmax=3` comes from Cr,
//! not luma). Found by the local fuzz_decode_diff_c 10,000-iteration smoke
//! sweep (artifact `acc_x86_5327.jpg`).
//!
//! Our colour/upsample pipeline assumes luma is the maximally-sampled
//! component, so the chroma upsample factor `y_width / cr_w = 8 / 24` truncates
//! to 0. Before this fix the decoder hard-rejected with
//! `CorruptData("chroma upsample factor zero…")`, which made the differential
//! decode fuzzer panic "drop-in regression" because djpeg decodes the image.
//!
//! Contract pinned here:
//! - **Strict** mode still rejects (the feature is genuinely unsupported;
//!   pixel-correct decoding is tracked as P4-21).
//! - **Lenient** mode recovers: it returns a 15x9 RGB raster matching djpeg's
//!   dimensions and records a `DecodeWarning`, so lenient decode stays "at
//!   least as accepting as the reference".

